CREATE TABLE __schema__.poi (
    locationid UUID PRIMARY KEY REFERENCES __schema__.location(locationid) ON DELETE CASCADE,
    elementtype TEXT NOT NULL CHECK (elementtype IN ('node', 'way', 'relation')),
    elementid BIGINT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('attraction', 'restaurant', 'hotel')),
    typename TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    imageurl TEXT,
    sourceadcode CHAR(12),
    sourceurl TEXT NOT NULL,
    UNIQUE (elementtype, elementid)
);

COMMENT ON TABLE __schema__.poi IS '从 OpenStreetMap 提取的旅行相关地点';
COMMENT ON COLUMN __schema__.poi.locationid IS '统一地点编号';
COMMENT ON COLUMN __schema__.poi.elementtype IS 'OSM 元素类型';
COMMENT ON COLUMN __schema__.poi.elementid IS 'OSM 元素编号';
COMMENT ON COLUMN __schema__.poi.category IS '景点、餐饮或住宿分类';
COMMENT ON COLUMN __schema__.poi.typename IS 'OSM 原始类型标签';
COMMENT ON COLUMN __schema__.poi.address IS '可用地址标签组合';
COMMENT ON COLUMN __schema__.poi.imageurl IS '合法 HTTP(S) 图片地址';
COMMENT ON COLUMN __schema__.poi.sourceadcode IS 'OSM 明确提供的十二位国标行政区代码';
COMMENT ON COLUMN __schema__.poi.sourceurl IS 'OpenStreetMap 原始记录链接';

CREATE TABLE __schema__.boundary (
    regionid UUID PRIMARY KEY REFERENCES __schema__.region(regionid) ON DELETE CASCADE,
    sourceid SMALLINT NOT NULL REFERENCES __schema__.source(sourceid),
    centergeom geometry(Point, 4326),
    boundarygeom geometry(MultiPolygon, 4326),
    originalsystem TEXT NOT NULL,
    conversionmethod TEXT NOT NULL
);

COMMENT ON TABLE __schema__.boundary IS '行政区中心点和多边形边界';
COMMENT ON COLUMN __schema__.boundary.regionid IS '边界所属行政区';
COMMENT ON COLUMN __schema__.boundary.sourceid IS '边界数据来源';
COMMENT ON COLUMN __schema__.boundary.centergeom IS '转换后的 WGS-84 中心点';
COMMENT ON COLUMN __schema__.boundary.boundarygeom IS '转换并修复后的 WGS-84 多边形';
COMMENT ON COLUMN __schema__.boundary.originalsystem IS '原始坐标系，当前为 GCJ-02';
COMMENT ON COLUMN __schema__.boundary.conversionmethod IS '坐标转换算法说明';

CREATE TABLE __schema__.regionmatch (
    locationid UUID PRIMARY KEY REFERENCES __schema__.location(locationid) ON DELETE CASCADE,
    regionid UUID REFERENCES __schema__.region(regionid),
    matchmethod TEXT NOT NULL CHECK (matchmethod IN ('sourcecode', 'spatial', 'unmatched')),
    confidence NUMERIC(4, 3) NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    matchedat TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (
        (matchmethod = 'unmatched' AND regionid IS NULL AND confidence = 0)
        OR (matchmethod <> 'unmatched' AND regionid IS NOT NULL)
    )
);

COMMENT ON TABLE __schema__.regionmatch IS '自然地名和 POI 挂接到行政树的结果';
COMMENT ON COLUMN __schema__.regionmatch.locationid IS '待挂接地点编号';
COMMENT ON COLUMN __schema__.regionmatch.regionid IS '确认的最深行政区，无法匹配时为空';
COMMENT ON COLUMN __schema__.regionmatch.matchmethod IS '来源代码、空间落区或未匹配';
COMMENT ON COLUMN __schema__.regionmatch.confidence IS '固定且可解释的匹配置信度';
COMMENT ON COLUMN __schema__.regionmatch.matchedat IS '执行匹配的时间';

-- catalogindexes
CREATE INDEX regionparentidx ON __schema__.region(parentid);
CREATE INDEX regionpathidx ON __schema__.region USING gist(path);
CREATE INDEX locationnameexactidx ON __schema__.locationname(normalizedname, priority DESC);
CREATE INDEX locationnametrigramidx ON __schema__.locationname USING gin(normalizedname gin_trgm_ops);
CREATE INDEX locationpointidx ON __schema__.location USING gist(pointgeom);
CREATE INDEX boundarygeomidx ON __schema__.boundary USING gist(boundarygeom);
CREATE INDEX locationsourceididx ON __schema__.locationsource(locationid);
CREATE INDEX regionmatchregionidx ON __schema__.regionmatch(regionid);
CREATE INDEX geoplacefeatureidx ON __schema__.geoplace(featureclass, featurecode);
CREATE INDEX poicategoryidx ON __schema__.poi(category);

