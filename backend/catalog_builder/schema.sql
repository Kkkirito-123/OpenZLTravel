COMMENT ON COLUMN __schema__.geoplace.geonameid IS 'GeoNames 官方记录编号';
COMMENT ON COLUMN __schema__.geoplace.asciiname IS 'GeoNames ASCII 名称';
COMMENT ON COLUMN __schema__.geoplace.featureclass IS 'GeoNames 地理要素大类';
COMMENT ON COLUMN __schema__.geoplace.featurecode IS 'GeoNames 地理要素代码';
COMMENT ON COLUMN __schema__.geoplace.countrycode IS '国家或地区代码';
COMMENT ON COLUMN __schema__.geoplace.admin1 IS 'GeoNames 一级行政代码';
COMMENT ON COLUMN __schema__.geoplace.admin2 IS 'GeoNames 二级行政代码';
COMMENT ON COLUMN __schema__.geoplace.admin3 IS 'GeoNames 三级行政代码';
COMMENT ON COLUMN __schema__.geoplace.admin4 IS 'GeoNames 四级行政代码';
COMMENT ON COLUMN __schema__.geoplace.population IS '人口数，来源缺失时为零';
COMMENT ON COLUMN __schema__.geoplace.elevation IS '来源提供的海拔';
COMMENT ON COLUMN __schema__.geoplace.dem IS '数字高程模型高度';
COMMENT ON COLUMN __schema__.geoplace.timezone IS '时区名称';
